import { mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { createFixture, SANDBOX } from '../test/live/fixture.mjs';
import { stripAnsi } from '../test/live/case.mjs';
const SESSION = 'gjcdash-probewheel';
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const dir = join(SANDBOX, 'probe-wheel');
rmSync(dir, { recursive: true, force: true });
const state = join(dir, 'state'); const layout = 'abcdef012345';
mkdirSync(join(state, 'slots', layout, 'roles'), { recursive: true });
mkdirSync(join(state, 'data', 'scope1'), { recursive: true });
const phases = [{ name: 'P', tasks: Array.from({ length: 40 }, (_, i) => ({ content: `row-${i + 1}`, status: 'pending' })) }];
writeFileSync(join(state, 'data', 'scope1', 'todo.json'), JSON.stringify({ schema: 'gjc-herdr-dashboard/todo/1', updatedAt: 1, phases, empty: false, sourceError: null }));
writeFileSync(join(state, 'slots', layout, 'slot.json'), JSON.stringify({ schema: 'gjc-herdr-dashboard/slot/1', layoutKey: layout, scope: { scopeKey: 'scope1', scopeEpoch: 1, sessionId: 's' }, roles: { todo: { state: 'ready', token: 'tok', paneId: 'w1:p1' } } }));
const fixture = createFixture({ session: SESSION, evidenceDir: dir, logDir: dir });
const ESC = String.fromCharCode(27);
try {
  await fixture.startSession();
  const ws = fixture.createWorkspace({ cwd: dir, label: 'pw' });
  const pane = ws.rootPaneId;
  const viewer = join(process.cwd(), 'src', 'viewers', 'todo', 'viewer.mjs');
  fixture.sendText(pane, `node "${viewer}" --state "${state}" --layout ${layout} --role todo --token tok --pane ${pane}`);
  fixture.sendKeys(pane, 'enter');
  await sleep(4000);
  const top = () => { const ls = stripAnsi(fixture.readPane(pane)).split(/\r?\n/); return ls.filter((l) => /row-\d+/.test(l)).length + " rows, first: " + ls.find((l) => /row-\d+/.test(l)) + ", pane lines " + ls.length; };
  console.log('start      ', top());
  fixture.sendText(pane, `${ESC}[<65;5;4M`); await sleep(1500);
  console.log('after wheel', top(), '|', stripAnsi(fixture.readPane(pane)).split(/\r?\n/).filter(Boolean).at(-1));
  fixture.sendText(pane, `${ESC}[<65;5;4M`); await sleep(1500);
  console.log('after wheel2', top()); console.log(stripAnsi(fixture.readPane(pane)).split(/\r?\n/).slice(0,8).join("\n"));
  fixture.sendKeys(pane, 'q');
} finally { await fixture.cleanup(); }
