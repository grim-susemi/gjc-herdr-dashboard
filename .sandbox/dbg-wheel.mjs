import { EventEmitter } from 'node:events';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { startViewer, parseViewerArgs } from '../src/viewers/todo/viewer.mjs';
const state = join(process.cwd(), '.sandbox', 'dbg-state');
const layout = 'abcdef012345';
mkdirSync(join(state, 'slots', layout), { recursive: true });
mkdirSync(join(state, 'data', 'scope1'), { recursive: true });
const phases = [{ name: 'P', tasks: Array.from({ length: 24 }, (_, i) => ({ content: `row-${i + 1}`, status: 'pending' })) }];
writeFileSync(join(state, 'data', 'scope1', 'todo.json'), JSON.stringify({ schema: 'gjc-herdr-dashboard/todo/1', updatedAt: 1, phases, empty: false, sourceError: null }));
writeFileSync(join(state, 'slots', layout, 'slot.json'), JSON.stringify({ schema: 'gjc-herdr-dashboard/slot/1', layoutKey: layout, scope: { scopeKey: 'scope1', scopeEpoch: 1, sessionId: 's' }, roles: { todo: { state: 'ready', token: 'tok', paneId: 'p' } } }));
const input = new EventEmitter(); input.isTTY = true; input.setRawMode = () => {}; input.resume = () => {};
const writes = [];
const output = new EventEmitter(); output.isTTY = true; output.columns = 60; output.rows = 14; output.write = (s) => { writes.push(s); return true; };
const options = parseViewerArgs(['--state', state, '--layout', layout, '--role', 'todo', '--token', 'tok', '--pane', 'p']);
const viewer = await startViewer(options, { input, output, interactive: true, watchFocus: async () => () => {} });
const top = () => viewer.frame.lines.find((l) => /row-\d+/.test(l));
console.log('start', top(), JSON.stringify({ scroll: viewer.frame.scroll, bodyRows: viewer.frame.bodyRows, bodyLen: viewer.frame.bodyLines.length }));
input.emit('data', Buffer.from('\x1b[<65;5;4M'));
await new Promise((r) => setTimeout(r, 200));
console.log('after wheel', top(), JSON.stringify({ scroll: viewer.frame.scroll, follow: viewer.state?.prefs?.follow }));
await new Promise((r) => setTimeout(r, 1500));
console.log('after 1.5s', top(), viewer.frame.scroll);
await viewer.stop?.();
process.exit(0);
